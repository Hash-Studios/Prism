import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const arb = JSON.parse(readFileSync(resolve(root, 'lib/l10n/app_en.arb'), 'utf8'));
const copy = Object.fromEntries(Object.entries(arb).filter(([key, value]) => key.startsWith('duoWeb') && typeof value === 'string'));
if (!Object.keys(copy).length) throw new Error('Missing Duo web copy in English ARB');
const output = '// Generated by tool/generate_duo_web_copy.mjs from lib/l10n/app_en.arb.\n' +
  `export const duoCopy = ${JSON.stringify(copy, null, 2)} as const;\n`;
const path = resolve(root, 'web/lib/duo-copy.generated.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) { console.error('Duo web copy drift'); process.exitCode = 1; }
} else { writeFileSync(path, output); }
