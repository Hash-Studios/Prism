import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(resolve(root, 'shared/duo_reveal.json'), 'utf8'));
const members = Object.entries(spec).filter(([key]) => key !== 'source');
const derived = [
  ['foldedWidthFraction', 'canvasHeight * outerWidth / outerHeight / canvasWidth'],
  ['foldedLeftFraction', '1 - foldedWidthFraction'],
];
const banned = JSON.parse(readFileSync(resolve(root, 'shared/duo_banned_phrases.json'), 'utf8'));
const guard = `\nexport const DUO_BANNED_PHRASES = [${banned.map(phrase => JSON.stringify(phrase)).join(', ')}] as const;
export function normalizeDuoText(value: string): string {
  return value.normalize("NFKD").replace(new RegExp("\\\\p{M}", "gu"), "").toLowerCase()
    .replace(new RegExp("\\\\p{Cf}", "gu"), "").replace(new RegExp("[^\\\\p{L}\\\\p{N}]+", "gu"), " ").trim();
}
export function hasBannedDuoPhrase(value: string): boolean {
  const normalized = " " + normalizeDuoText(value) + " ";
  return DUO_BANNED_PHRASES.some((phrase) => normalized.includes(" " + normalizeDuoText(phrase) + " "));
}
`;
const ts = '// Generated by tool/generate_duo_reveal.mjs.\n' +
  members.map(([k, v]) => `const ${k} = ${JSON.stringify(v)};`).join('\n') + '\n' +
  derived.map(([k, v]) => `const ${k} = ${v};`).join('\n') + '\n' +
  `export const DUO_REVEAL_SPEC = {${[...members, ...derived].map(([k]) => k).join(', ')}} as const;\n`;
const dart = '// Generated by tool/generate_duo_reveal.mjs.\nabstract final class DuoRevealSpec {\n' +
  members.map(([k, v]) => `  static const ${k} = ${JSON.stringify(v).replaceAll('"', "'")};`).join('\n') + '\n' +
  derived.map(([k, v]) => `  static const ${k} = ${v};`).join('\n') + '\n}\n';
const outputs = new Map([
  ['lib/core/wallpaper/duo_reveal_spec.g.dart', dart],
  ...['functions/src', 'infra/cloudflare/worker/src', 'web/lib'].map(p => [`${p}/duo_reveal_spec.ts`, ts + guard]),
]);
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    let actual;
    try { actual = readFileSync(target, 'utf8'); } catch {}
    if (actual !== content) { console.error(`Generated spec drift: ${path}`); process.exitCode = 1; }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
